package com.sfaasproject.stf.operations.event;

import static org.junit.jupiter.api.Assertions.assertEquals;

import com.zaxxer.hikari.HikariDataSource;
import java.time.Clock;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;

class JdbcBEventOutboxTest {
    @Test
    void retryPublishesChildAfterReleasingParentConnection() {
        try (var pool = new HikariDataSource()) {
            pool.setJdbcUrl("jdbc:h2:mem:nested_outbox");
            pool.setMaximumPoolSize(1);
            pool.setConnectionTimeout(1000);
            var jdbc = new JdbcTemplate(pool);
            jdbc.execute("CREATE TABLE backend_event_outbox (outbox_id BIGINT GENERATED BY DEFAULT"
                    + " AS IDENTITY PRIMARY KEY, event_type VARCHAR(80), payload VARCHAR(1000),"
                    + " created_at TIMESTAMP, published_at TIMESTAMP)");
            var events = new AtomicReference<BEventPublisher>();
            var delivered = new ArrayList<String>();
            var outbox = new JdbcBEventOutbox(jdbc, new DataSourceTransactionManager(pool), raw -> {
                var event = (V7Events.CountsCommitted) raw;
                delivered.add(event.eventId());
                if (event.eventId().equals("parent")) {
                    events.get().publish(new V7Events.CountsCommitted("child", 2, 0));
                }
            }, Clock.systemUTC());
            events.set(new BEventPublisher(raw -> {}, outbox));
            outbox.append(new V7Events.CountsCommitted("parent", 1, 0));
            outbox.retryPending();
            assertEquals(List.of("parent", "child"), delivered);
            assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM backend_event_outbox"
                    + " WHERE published_at IS NULL", Integer.class));
            outbox.retryPending();
            assertEquals(2, delivered.size());
        }
    }
}
